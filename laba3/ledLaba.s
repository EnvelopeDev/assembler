main:
    # Заполняем массив A числами 0-499
    la t0, A
    li t1, 0
    li t2, 500
    
fill_loop:
    sw t1, 0(t0)
    addi t0, t0, 4
    addi t1, t1, 1
    blt t1, t2, fill_loop

    # Поиск элементов с 2 единицами в бинарном представлении
    la s0, A           # Адрес массива A
    la s2, B_adr       # Адрес массива для адресов
    li s3, 0           # Счетчик найденных элементов
    li s4, 0           # Текущая позиция

search_loop:
    li t5, 500
    bge s4, t5, print_results
    lw a0, 0(s0)       # Загружаем элемент из A
    li t0, 0           # Счетчик единиц
    mv t1, a0          # Копируем число для обработки

count_bits:
    beqz t1, check_count
    andi t2, t1, 1     # Проверяем младший бит
    add t0, t0, t2     # Увеличиваем счетчик если бит = 1
    srli t1, t1, 1     # Сдвигаем вправо
    j count_bits

check_count:
    li t2, 2
    bne t0, t2, next_element
    
    # Нашли элемент с 2 единицами
    sw s0, 0(s2)       # Сохраняем адрес в B_adr
    addi s2, s2, 4
    addi s3, s3, 1

next_element:
    addi s0, s0, 4
    addi s4, s4, 1
    j search_loop

print_results:
    sw s3, count, t0
    
    # Вывод "Total found: "
    la a0, found_msg
    li a7, 4
    ecall
    
    # Вывод количества найденных
    mv a0, s3
    li a7, 1
    ecall
    
    # Перевод строки
    la a0, nl
    li a7, 4
    ecall
    
    # Вывод всех найденных элементов
    la s2, B_adr
    li s4, 0

print_loop:
    bge s4, s3, exit
    
    # Вывод "Addr:"
    la a0, addr_msg
    li a7, 4
    ecall
    
    # Вывод адреса в hex
    lw a0, 0(s2)
    li a7, 34
    ecall
    
    # Вывод " Val:"
    la a0, val_msg
    li a7, 4
    ecall
    
    # Вывод значения (позиция = значение)
    lw t0, 0(s2)        # Загружаем адрес из B_adr
    la t1, A            # ЗАГРУЖАЕМ БАЗОВЫЙ АДРЕС A!
    sub t2, t0, t1      # Вычисляем смещение
    srli a0, t2, 2      # Делим на 4 чтобы получить позицию/значение
    li a7, 1
    ecall
    
    # Вывод " Bin:"
    la a0, bin_msg
    li a7, 4
    ecall
    
    # Вывод в двоичном формате
    lw t0, 0(s2)
    la t1, A            # ЗАГРУЖАЕМ БАЗОВЫЙ АДРЕС A СНОВА!
    sub t2, t0, t1
    srli a0, t2, 2      # Позиция = значение
    li a7, 35
    ecall
    
    # Перевод строки
    la a0, nl
    li a7, 4
    ecall
    
    # Следующий элемент
    addi s2, s2, 4
    addi s4, s4, 1
    j print_loop

